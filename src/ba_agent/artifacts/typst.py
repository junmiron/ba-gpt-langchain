def find_typst() -> str | None:
    """Resolve the Typst executable, or None if no renderer is available."""
    env = os.environ.get("BA_TYPST_BIN")
    if env and Path(env).is_file():
        return env
    on_path = shutil.which("typst")
    if on_path:
        return on_path
    for candidate in sorted((PROJECT_ROOT / "vendor" / "typst").rglob("typst*.exe")):
        if candidate.is_file():
            return str(candidate)
    for candidate in sorted((PROJECT_ROOT / "vendor" / "typst").rglob("typst")):
        if candidate.is_file():
            return str(candidate)
    return None


def typst_version(binary: str) -> str:
    try:
        out = subprocess.run([binary, "--version"], capture_output=True, text=True, timeout=15)
        return (out.stdout or "").strip()
    except Exception:  # noqa: BLE001 - version probing is informational only
        return ""


def _escape(value: str) -> str:
    """Make plain text safe inside Typst markup."""
    return (value or "").replace("\\", "\\\\").replace("#", "\\#").replace("$", "\\$").replace("_", "\\_")


def _typst_string(value: str) -> str:
    return _escape((value or "").strip()).replace('"', '\\"')


# ---------------------------------------------------------------- markdown → typst

_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_FENCE_RE = re.compile(r"^\s*```")
_TABLE_ROW_RE = re.compile(r"^\s*\|.*\|\s*$")
_SEP_ROW_RE = re.compile(r"^\s*\|[\s|:-]+\|\s*$")
_LIST_RE = re.compile(r"^(\s*)([-*+]\s+)(.*)$")
_ORDERED_RE = re.compile(r"^(\s*)(\d+\.\s+)(.*)$")
_QUOTE_RE = re.compile(r"^\s*>\s?(.*)$")


def inline_markdown(text: str) -> str:
    """Bold/italic/links/code in one line of Markdown → Typst.

    Order matters: Typst bold is `*x*` and italic is `_x_`. Converting `**x**` first would leave `*x*`,
    which the italic rule then mis-reads as emphasis. Match single-asterisk italic before bold.
    """
    text = _escape(text)
    text = re.sub(r"(?<![\w*])\*([^*\s][^*]*?)\*(?![\w*])", r"_\1_", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"*\1*", text)
    text = re.sub(r"`([^`]+)`", r"raw(`\1`)", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'link("\2", \1)', text)
    return text


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _column_widths(rows: list[list[str]]) -> list[int]:
    """Proportional column widths so an ID column stays narrow and prose columns get the room."""
    if not rows:
        return []
    columns = list(zip(*rows, strict=False))
    minimums, weights = [], []
    for column in columns:
        words = [len(word) for cell in column for word in cell.split()]
        longest = max(words) if words else 4
        minimums.append((longest + 1) * GLYPH_ADVANCE_PT + CELL_PAD_PT)
        weights.append(sum(len(cell) for cell in column) or 1)

    total_min = sum(minimums)
    if total_min >= CONTENT_WIDTH_PT:
        fractions = [minimum / total_min * 100 for minimum in minimums]
    else:
        spare = CONTENT_WIDTH_PT - total_min
        total_weight = sum(weights) or 1
        fractions = [
            (minimum + spare * weight / total_weight) / CONTENT_WIDTH_PT * 100
            for minimum, weight in zip(minimums, weights, strict=False)
        ]
    widths = [max(6, min(70, round(fraction))) for fraction in fractions]
    widest = widths.index(max(widths))
    widths[widest] += 100 - sum(widths)
    return widths


def _header_expr(cell: str) -> str:
    """Header cells are already bold by table styling, so Markdown emphasis is stripped, not doubled."""
    plain = re.sub(r"\*\*(.+?)\*\*", r"\1", cell or "")
    plain = re.sub(r"(?<!\w)\*([^*\s][^*]*?)\*(?!\w)", r"\1", plain)
    return f'text("{_typst_string(plain)}", fill: white, weight: "bold")'


_INLINE_TOKEN_RE = re.compile(r"\*\*(.+?)\*\*|\*([^*\s][^*]*?)\*|`([^`]+)`|\[([^\]]+)\]\(([^)]+)\)")


def _code_string(value: str) -> str:
    return (value or "").replace("\\", "\\\\").replace('"', '\\"')


def _inline_code(text: str) -> str:
    """Inline Markdown emphasis in one line -> a Typst *code-mode* expression.

    Table cells are parsed as code, where `*x*` is a syntax error: emphasis has to be spelled as the
    `strong`/`emph`/`raw`/`link` functions instead.
    """
    parts: list[str] = []
    position = 0
    text = text or ""
    for match in _INLINE_TOKEN_RE.finditer(text):
        if match.start() > position:
            parts.append(f'"{_code_string(text[position : match.start()])}"')
        if match.group(1) is not None:
            parts.append(f'strong("{_code_string(match.group(1))}")')
        elif match.group(2) is not None:
            parts.append(f'emph("{_code_string(match.group(2))}")')
        elif match.group(3) is not None:
            parts.append(f'raw("{_code_string(match.group(3))}")')
        else:
            parts.append(f'link("{_code_string(match.group(5))}", "{_code_string(match.group(4))}")')
        position = match.end()
    if position < len(text):
        parts.append(f'"{_code_string(text[position:])}"')
    # In code mode a cell must be one expression; adjacent content is joined with `+`, not with a
    # comma (a comma builds an array, which `table` rejects).
    return parts[0] if len(parts) == 1 else " + ".join(parts)


def _content_expr(cell: str) -> str:
    """One table cell -> a Typst expression, keeping real markup and multi-line cells."""
    lines = [line.strip() for line in (cell or "").split("\n") if line.strip()]
    if not lines:
        return '"\u2014"'
    if len(lines) == 1:
        return _inline_code(lines[0])
    items: list[str] = []
    for index, line in enumerate(lines):
        if index:
            items.append("linebreak()")
        items.append(_inline_code(line))
    return " + ".join(items)


def _table_to_typst(lines: list[str]) -> list[str]:
    header = _cells(lines[0])
    rows = [_cells(line) for line in lines[2:]]
    widths = _column_widths([header, *rows])
    out = ["#table(", f"  columns: ({', '.join(f'{w}%' for w in widths)}),", '  stroke: 0.4pt + rgb("#d0d5dd"),']
    out.append('  fill: (x, y) => if y == 0 { rgb("#111827") } else if y / 2 * 2 == y { rgb("#f6f8fa") },')
    out.append("  inset: (x: 6pt, y: 5pt),")
    out.append("  table.header(" + ", ".join(_header_expr(cell) for cell in header) + "),")
    for row in rows:
        out.append("  " + ", ".join(_content_expr(cell) for cell in row) + ",")
    out.append(")")
    return out


def markdown_to_typst(markdown: str) -> str:
    """Hand-generated Typst body — no pandoc, no post-processing patch-ups."""
    lines = (markdown or "").replace("\r\n", "\n").split("\n")
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]

        if _FENCE_RE.match(line):
            language = line.strip().lstrip("`").strip().lower()
            block: list[str] = []
            index += 1
            while index < len(lines) and not _FENCE_RE.match(lines[index]):
                block.append(lines[index])
                index += 1
            index += 1
            if language == "mermaid":
                continue  # diagrams are rendered as figures elsewhere
            body = "\n".join(block)
            if body.strip():
                out.append(f'raw(block: true, dedent: true, "{_typst_string(body)}")')
            continue

        if _TABLE_ROW_RE.match(line):
            table: list[str] = [line]
            index += 1
            while index < len(lines) and _TABLE_ROW_RE.match(lines[index]):
                table.append(lines[index])
                index += 1
            if len(table) >= 2 and _SEP_ROW_RE.match(table[1]):
                out.extend(_table_to_typst(table))
            else:
                out.extend(inline_markdown(row) for row in table)
            out.append("")
            continue

        heading = _HEADING_RE.match(line)
        if heading:
            level = len(heading.group(1))
            out.append(f"{'=' * level} {inline_markdown(heading.group(2))}")
            out.append("")
            index += 1
            continue

        quote = _QUOTE_RE.match(line)
        if quote:
            out.append(f"#quote([{inline_markdown(quote.group(1))}])")
            out.append("")
            index += 1
            continue

        match = _LIST_RE.match(line) or _ORDERED_RE.match(line)
        if match:
            indent = len(match.group(1)) // 2
            marker = match.group(2)
            content = inline_markdown(match.group(3))
            out.append("  " * indent + f"{marker}{content}")
            index += 1
            continue

        if not line.strip():
            out.append("")
        else:
            out.append(inline_markdown(line.strip()))
        index += 1

    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


