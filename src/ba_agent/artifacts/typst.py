"""Deliverable rendering: Markdown → Typst → PDF (Phase 2 of the redesign).

Typst is chosen over pandoc/ReportLab because it produces a *vector* PDF with a real linked outline,
repeating table headers across page breaks, and Mermaid SVG diagrams whose labels stay selectable text.
Pandoc is not in the path at all: the `.typ` source is generated here, so there is no
"convert Markdown then patch the output" step to break.

Binary discovery (:func:`find_typst`), in order:
  1. ``BA_TYPST_BIN``
  2. ``typst`` on PATH
  3. ``vendor/typst/**/typst.exe`` (the vendored, gitignored portable build)

If none is found the caller falls back to ReportLab + svglib (:mod:`ba_agent.artifacts.reportlab_pdf`),
which is pure Python and needs no binary. Rendering never fails a run: both paths return ``None`` on
error and the HTML/Markdown deliverables still exist.
"""

