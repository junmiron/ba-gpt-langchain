def build_typst_source(title: str, version: str, date: str, status: str, body: str) -> str:
    return (
        _TEMPLATE.replace("__TITLE__", _typst_string(title))
        .replace("__VERSION__", _typst_string(version))
        .replace("__DATE__", _typst_string(date))
        .replace("__STATUS__", _typst_string(status))
        .replace("__BODY__", body)
    )


def render_pdf(
    spec_markdown: str,
    pdf_path: Path,
    *,
    title: str,
    version: str = "0.1",
    date: str = "",
    status: str = "Draft",
    diagrams: list[dict[str, Any]] | None = None,
    working_dir: Path | None = None,
) -> dict[str, Any]:
    """Typeset the spec with Typst. Returns ``{"ok": bool, "engine": str, "error": str | None}``."""
    binary = find_typst()
    if not binary:
        return {"ok": False, "engine": "typst", "error": "typst binary not found"}

    if working_dir is None:
        raise ValueError("render_pdf requires a working_dir; band SVGs must not be written to the caller's cwd")
    directory = working_dir
    directory.mkdir(parents=True, exist_ok=True)
    figures = prepare_diagrams(diagrams or [], directory)

    from datetime import date as _date

    body = markdown_to_typst(spec_markdown)
    if figures:
        body += "\n\n" + figures_to_typst(figures)
    source = build_typst_source(title, version, date or _date.today().isoformat(), status, body)
    typst_path = directory / "functional_specification.typ"
    typst_path.write_text(source, encoding="utf-8")

    command = [binary, "compile", str(typst_path), str(pdf_path)]
    font_dir = PROJECT_ROOT / "vendor" / "fonts"
    if font_dir.is_dir():
        command.insert(1, f"--font-path={font_dir}")
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=180)
    except Exception as exc:  # noqa: BLE001 - a render failure must not fail the deliverable
        return {"ok": False, "engine": "typst", "error": f"{type(exc).__name__}: {exc}"}
    if result.returncode != 0 or not pdf_path.exists():
        return {
            "ok": False,
            "engine": "typst",
            "error": (result.stderr or result.stdout or "typst failed").strip()[:400],
        }
    return {
        "ok": True,
        "engine": "typst",
        "error": None,
        "pages": pdf_pages(pdf_path),
        "bytes": pdf_path.stat().st_size,
    }


def pdf_pages(pdf_path: Path) -> int:
    try:
        from pypdf import PdfReader

        return len(PdfReader(str(pdf_path)).pages)
    except Exception:  # noqa: BLE001 - QA is optional
        return 0
