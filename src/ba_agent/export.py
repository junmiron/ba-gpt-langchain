def build_html(state: SessionState, spec_markdown: str, svg: str = "") -> str:
    from html import escape

    title = state.plan.project_name if state.plan and state.plan.project_name else state.title
    marked_js = _load_vendor("marked.min.js")
    svg_block = ""
    if svg:
        svg_block = ('<details class="svg" open><summary>Process diagram (SVG)</summary>'
                     f'<div style="overflow:auto">{svg}</div></details>')
    return _HTML_TEMPLATE.format(
        title=escape(title),
        generated=date.today().isoformat(),
        session_id=state.session_id,
        questions=len(state.questions),
        requirements=len(state.requirements()),
        escaped_spec=escape(spec_markdown[:400_000]),
        svg_block=svg_block,
        marked_js=marked_js or "/* marked.js not vendored — showing raw markdown */",
        json_spec=json.dumps(spec_markdown),
    )


def _load_vendor(filename: str) -> str:
    for candidate in (Path(__file__).resolve().parent / "web" / "vendor" / filename,):
        if candidate.exists():
            try:
                return candidate.read_text(encoding="utf-8")
            except OSError:
                return ""
    return ""


def try_pdf(html_path: Path, pdf_path: Path) -> WrittenArtifact | None:
    """Optional PDF. Silently skipped when weasyprint is not installed (HTML prints to the same result)."""
    if shutil.which("weasyprint") is None:
        try:
            import weasyprint  # noqa: F401
        except Exception:
            return None
    try:
        from weasyprint import HTML

        HTML(filename=str(html_path)).write_pdf(str(pdf_path))
        data = pdf_path.read_bytes()
        return WrittenArtifact(name=pdf_path.name, path=str(pdf_path), bytes=len(data),
                               sha256=sha256_text(f"binary:{len(data)}"))
    except Exception:
        return None


def metrics_summary(state: SessionState) -> dict:
    """Human-readable run summary shown at the end of the timeline and stored in metadata."""

    def fmt(seconds: float) -> str:
        seconds = int(seconds or 0)
        return f"{seconds // 60}m {seconds % 60:02d}s" if seconds >= 60 else f"{seconds}s"

    lines = [f"Model calls: {int(state.metrics.get('calls', 0))}",
             f"Model time: {fmt(state.metrics.get('model_seconds', 0))}"]
    if state.metrics.get("questions"):
        lines.append(f"Questions asked: {int(state.metrics['questions'])}")
    return {"text": " · ".join(lines)}


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")[:60] or "session"
