"""Deliverable assembly — the deterministic replacement for v1's ``terminate_agent`` MCP pipeline.

Everything here is pure Python and works on Windows with no system packages: markdown, JSONL, Mermaid source, an
optional SVG (only if you explicitly enabled a renderer) and a **self-contained HTML** deliverable that prints to
a clean PDF from the browser. ``weasyprint`` is used for a real PDF only when it happens to be installed.
"""

from __future__ import annotations

