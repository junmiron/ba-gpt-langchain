"""Deliverable assembly — the deterministic replacement for v1's ``terminate_agent`` MCP pipeline.

Everything here is pure Python and needs no model call: the Markdown spec, the interview JSONL, Mermaid source
plus an SVG when a renderer is available, a **self-contained HTML** deliverable with a linked Contents block,
and a real typeset PDF. Typst is used when a `typst` binary is discoverable (`BA_TYPST_BIN`, PATH or
`vendor/typst/`), otherwise ReportLab + svglib. A PDF failure never fails the run — Markdown and HTML still
ship, and `pdf_qa.json` records what the QA gate checked.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import UTC, date, datetime
from html import escape
from pathlib import Path
from typing import Any

from .artifacts import render_spec_pdf
from .context import render_summary_markdown
from .schemas import ArtifactRef, Phase, SessionState
from .services import Services
from .spec import assemble_spec


@dataclass
class WrittenArtifact:
    name: str
    path: str
    bytes: int
    sha256: str

    def to_ref(self) -> ArtifactRef:
        return ArtifactRef(name=self.name, kind="file", path=self.path, bytes=self.bytes, sha256=self.sha256)


def _write(directory: Path, name: str, content: str | bytes) -> WrittenArtifact:
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / name
    if isinstance(content, str):
        data = content.encode("utf-8")
    else:
        data = content
    target.write_bytes(data)
    return WrittenArtifact(name=name, path=str(target), bytes=len(data), sha256=hashlib.sha256(data).hexdigest())


def _record(directory: Path, target: Path) -> WrittenArtifact:
    """Register a file that already exists in the deliverable folder (the diagram PNG is written at render
    time, so re-writing it here would just duplicate the bytes).

    The hash is over the raw bytes: decoding a PNG as UTF-8 with `errors="replace"` is lossy, so two
    different images could produce the same digest.
    """
    data = target.read_bytes()
    return WrittenArtifact(name=target.name, path=str(target), bytes=len(data), sha256=hashlib.sha256(data).hexdigest())


def write_deliverables(services: Services, state: SessionState) -> list[WrittenArtifact]:
    directory = services.config.out_dir(state.session_id)
    written: list[WrittenArtifact] = []

    spec_markdown = state.spec_markdown or assemble_spec(state)
    written.append(_write(directory, "functional_specification.md", spec_markdown))

    if state.summary:
        written.append(_write(directory, "requirements_summary.md", render_summary_markdown(state.summary)))

    qa_rows = services.store.list_qa(state.session_id)
    jsonl = "\n".join(json.dumps(row, ensure_ascii=False, default=str) for row in qa_rows)
    written.append(_write(directory, "interview.jsonl", jsonl + ("\n" if jsonl else "")))

    # The raw transcript, if the run started from one — it is the evidence behind the ledger entries.
    if (state.transcript or "").strip():
        written.append(_write(directory, "transcript.txt", state.transcript.strip() + "\n"))

    diagrams = state.diagrams or []
    for position, diagram in enumerate(diagrams, start=1):
        code = diagram.get("code") or ""
        if code:
            mmd = f"%% {state.title} — generated by BA agent (LangChain) on {date.today().isoformat()}\n{code}\n"
            written.append(_write(directory, f"process_diagram_{position}.mmd", mmd))
        if diagram.get("svg"):
            written.append(_write(directory, f"process_diagram_{position}.svg", diagram["svg"]))
        png_path = diagram.get("png_path") or ""
        if png_path:
            written.append(_record(directory, Path(png_path)))

    written.append(_write(directory, "deliverable.html", build_html(state, spec_markdown, diagrams)))

    pdf, engine, qa_report = write_pdf(
        directory, state, spec_markdown, diagrams, html_path=directory / "deliverable.html"
    )
    if pdf:
        written.append(pdf)

    metadata = build_metadata(state, gateway=services.gateway)
    # Which renderer produced the PDF, and why it fell back — the README tells users to look here.
    metadata["pdf_engine"] = engine or "none"
    metadata["pdf_available"] = pdf is not None
    # The QA verdict travels with the manifest, so a reviewer can tell whether the
    # deliverable is trustworthy without opening pdf_qa.json separately.
    metadata["qa"] = {
        "ok": bool(qa_report.get("ok")),
        "warnings": qa_report.get("warnings", []),
        "checks": qa_report.get("checks", {}),
    }
    written.append(_write(directory, "metadata.json", json.dumps(metadata, ensure_ascii=False, indent=2)))

    return written


def build_metadata(state: SessionState, gateway: Any | None = None) -> dict:
    from .spec import spec_stats

    metadata = {
        "session_id": state.session_id,
        "title": state.title,
        "project_name": state.plan.project_name if state.plan else state.title,
        "objective": state.plan.objective if state.plan else "",
        "brief": state.seed,
        "phase": state.phase.value,
        "status": state.status.value,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "subjects": [s.model_dump() for s in state.subjects],
        "questions_asked": len(state.questions),
        "requirements": [i.model_dump() for i in state.requirements()],
        "ledger_entries": len(state.ledger),
        "review_rounds": state.review_rounds,
        "gap_rounds": state.gap_round,
        "open_issues": [i.model_dump() for i in state.open_issues],
        "lint_report": state.lint_report,
        "model_overrides": state.model_overrides,
        "metrics": state.metrics,
        # Which phase ate the run. A 30-minute session is only diagnosable if you can see that the
        # interview was 19 of those minutes and the writer was 2.
        "phase_metrics": state.metrics.get("by_phase", {}),
        "spec_stats": spec_stats(state),
        #: Human-readable digest of effort spent, so a shipped bundle explains its own runtime.
        "run_summary": metrics_summary(state),
    }
    if gateway is not None:
        #: Which backend actually ran the session. A bundle produced on Strata and one produced on
        #: LM Studio are not comparable unless the record says which one it was.
        config = getattr(gateway, "config", None)
        if config is not None:
            profile = config.active_profile
            metadata["backend"] = {
                "provider": config.provider,
                "base_url": profile.base_url,
                "default_model": profile.default_model,
                "embedding_model": profile.embedding_model,
            }
        # Which rung of the structured-output ladder actually satisfied each call. A run that quietly
        # fell back to prompt-mode JSON for every step looks identical to a healthy run otherwise.
        metadata["structured_output"] = {
            "rung_counts": getattr(gateway, "rung_counts", {}),
            "learned_rung": getattr(gateway, "_learned_rung", {}),
        }
        # Effort actually spent. `metrics` tracks phase timing; this is the call volume behind it, which
        # is what tells you whether a run is slow because of retries or because it asked the model a lot.
        usage = getattr(gateway, "usage", {}) or {}
        metadata["llm_usage"] = {
            "calls": usage.get("calls", 0),
            "failures": usage.get("failures", 0),
            "prompt_chars": usage.get("prompt_chars", 0),
            "completion_chars": usage.get("completion_chars", 0),
        }
    return metadata


# --------------------------------------------------------------------------- HTML


def build_html(state: SessionState, spec_markdown: str, diagrams: list[dict]) -> str:
    """Self-contained HTML deliverable: rendered Markdown, linked Contents nav, inline SVG diagrams."""
    from .artifacts.html import build_html as _build

    meta = (
        f"Generated {date.today().isoformat()} · session <code>{escape(state.session_id)}</code> · "
        f"{len(state.questions)} interview questions · {len(state.requirements())} requirements"
    )
    title = state.plan.project_name if state.plan and state.plan.project_name else state.title
    return _build(title, spec_markdown, diagrams, meta=meta)


def document_status(state: SessionState) -> str:
    """A cover-page status a human can read: the phase enum value ("deliver") is an internal detail."""
    if state.phase is Phase.DONE:
        return "Approved draft" if state.approved_summary else "Draft for review"
    if state.approved_summary:
        return "Approved — drafting"
    return "Draft — awaiting approval"


def write_pdf(
    directory: Path,
    state: SessionState,
    spec_markdown: str,
    diagrams: list[dict],
    html_path: Path | None = None,
) -> tuple[WrittenArtifact | None, str | None, dict[str, Any]]:
    """Typeset the spec to PDF (Typst, else ReportLab).

    Returns ``(artifact, engine)`` — `(None, None)` if neither engine is available. A render failure never
    fails the run: the Markdown/HTML deliverables already exist. The QA report is written next to the PDF so
    a reviewer can see what the renderer actually verified — and it is written even when there is no PDF,
    because the HTML deliverable still has a QA gate (resolving TOC anchors) that must not be skipped just
    because typesetting failed.
    """
    pdf_path = directory / "functional_specification.pdf"
    result = render_spec_pdf(
        spec_markdown,
        pdf_path,
        title=state.plan.project_name if state.plan and state.plan.project_name else state.title,
        version=f"1.{state.review_rounds}",
        date=date.today().isoformat(),
        status=document_status(state),
        diagrams=diagrams,
        working_dir=directory,
    )

    from .artifacts.qa import audit_html, audit_pdf

    if result["ok"]:
        report = audit_pdf(pdf_path, spec_markdown, diagrams)
    else:
        report = {"ok": True, "checks": {}, "warnings": ["no PDF engine produced a file (Typst or ReportLab required)"]}

    if html_path and html_path.exists():
        html_report = audit_html(html_path)
        report["html"] = html_report
        report["ok"] = report["ok"] and html_report["ok"]
        report["warnings"] = report["warnings"] + html_report["warnings"]
    _write(directory, "pdf_qa.json", json.dumps(report, ensure_ascii=False, indent=2))

    if not result["ok"]:
        return None, None, report
    data = pdf_path.read_bytes()
    artifact = WrittenArtifact(
        name=pdf_path.name, path=str(pdf_path), bytes=len(data), sha256=hashlib.sha256(data).hexdigest()
    )
    return artifact, result["engine"], report


def metrics_summary(state: SessionState) -> dict:
    """Human-readable run summary shown at the end of the timeline and stored in metadata."""

    def fmt(seconds: float) -> str:
        seconds = int(seconds or 0)
        return f"{seconds // 60}m {seconds % 60:02d}s" if seconds >= 60 else f"{seconds}s"

    lines = [
        f"Model calls: {int(state.metrics.get('calls', 0))}",
        f"Model time: {fmt(state.metrics.get('model_seconds', 0))}",
    ]
    if state.metrics.get("questions"):
        lines.append(f"Questions asked: {int(state.metrics['questions'])}")

    # A run that took 25 minutes is only diagnosable if you can see which phase ate it. Without this
    # the reader cannot tell "the model is slow" from "the interview loop ran twice".
    phases = state.metrics.get("by_phase", {})
    slow = sorted(
        ((phase, entry) for phase, entry in phases.items() if entry.get("wall_seconds")),
        key=lambda item: -item[1]["wall_seconds"],
    )[:3]
    if slow:
        lines.append(
            "Slowest phases: "
            + ", ".join(f"{phase} {fmt(entry['wall_seconds'])} ({int(entry['calls'])} calls)" for phase, entry in slow)
        )
    return {"text": " · ".join(lines)}
