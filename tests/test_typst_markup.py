"""Typst source generation, checked as text.

Typst itself is optional (the binary may not be installed), but the markup it is fed is generated by
pure functions here, and a syntax error in that source is a silent zero-byte PDF. These tests assert
the generated Typst directly, so they run everywhere.
"""

from __future__ import annotations

from ba_agent.artifacts.typst import _content_expr, _header_expr, _table_to_typst, inline_markdown, markdown_to_typst


def test_links_in_a_table_cell_use_typst_link_not_markdown():
    cell = "See the [policy API](https://example.com/api) for details"
    expression = _content_expr(cell)
    assert 'link("https://example.com/api", "policy API")' in expression, expression
    # In code mode adjacent content must be joined with `+`; a comma builds an array and `table` rejects it.
    assert "," not in expression.replace('link("', "").replace('", "', ""), expression


def test_an_empty_table_cell_becomes_an_em_dash_not_a_blank_argument():
    assert _content_expr("") == '"\u2014"'
    assert _content_expr("   ") == '"\u2014"'
    assert _header_expr("") == 'text("", fill: white, weight: "bold")'


def test_a_multi_line_cell_is_joined_with_linebreak():
    expression = _content_expr("Uploads finish\nin under 10 seconds")
    assert "linebreak()" in expression, expression
    assert '"Uploads finish" + linebreak() + "in under 10 seconds"' in expression, expression


def test_header_cells_are_not_double_bold():
    header = _header_expr("**Priority**")
    assert header == 'text("Priority", fill: white, weight: "bold")', header


def test_a_markdown_table_produces_a_typst_table_with_column_widths():
    lines = [
        "| ID | Requirement | Acceptance |",
        "|---|---|---|",
        "| FR-001 | Submit claim | Under 10 s |",
        "| FR-002 | Track status | Within 1 s |",
    ]
    typst = "\n".join(_table_to_typst(lines))
    assert typst.startswith("#table(")
    assert "columns: (" in typst and "%)" in typst
    assert "table.header(" in typst
    assert '"FR-001"' in typst


def test_a_pipe_line_without_a_separator_row_stays_literal_text():
    body = markdown_to_typst("| one | two |\n")
    assert "#table(" not in body
    assert "one" in body


def test_fenced_code_becomes_raw_block_and_mermaid_is_dropped():
    body = markdown_to_typst('```json\n{"claim": "C-1"}\n```\n\n```mermaid\ngraph TD; A-->B;\n```\n')
    assert "raw(block: true, dedent: true," in body, body
    assert "claim" in body and body.count("raw(block: true") == 1
    assert "graph TD" not in body, "the mermaid source must not be printed as text — it is rendered as a figure"


def test_an_empty_code_fence_emits_nothing():
    body = markdown_to_typst("```\n```\n\nSome text.\n")
    assert "raw(block" not in body
    assert "Some text." in body


def test_inline_emphasis_survives_typst_escaping():
    assert inline_markdown("**bold** and *italic*") == "*bold* and _italic_"
    assert inline_markdown("`status_code`") == "raw(`status\\_code`)"
    assert inline_markdown("100% uptime & <5s") == "100% uptime & <5s", "typst needs no escaping here"
    assert inline_markdown("the #1 cause is $X") == "the \\#1 cause is \\$X"


def test_quotes_and_headings_are_emitted_as_typst_blocks():
    body = markdown_to_typst("## Scope\n\n> Legacy system.\n\n- item one\n  - nested\n")
    assert body.startswith("== Scope")
    assert "#quote([Legacy system.])" in body
    assert "- item one" in body
    assert "  - nested" in body
